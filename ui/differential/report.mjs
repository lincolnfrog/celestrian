/**
 * The drift report (`run.mjs --report <file>`): every diff of the run,
 * grouped by the verb its family is filed under, each with the sequence
 * that reaches it, both sides' values and which side is right. Written
 * from the run's own records and the known-drift list's words — nothing
 * here is typed twice. `notes` ({ familyId: text }, from `--notes
 * <json>`) adds a line per family: where a reviewer wants each drift
 * tied to an earlier finding, the ties live in that file, not here.
 */

import { FIELDS } from './fields.mjs';
import { showValue } from './normalize.mjs';

const cell = v => showValue(v).replace(/\|/g, '\\|');

/** The steps that reach a record: its journey's trace up to it, the
 * undo/redo probes left out (they are neutral pairs) unless the record
 * sits on one. */
function sequenceTo(pass, record) {
    const upTo = pass.trace.slice(0, record.at);
    let lastCall = upTo.length - 1;
    while (lastCall >= 0 && upTo[lastCall].probe) lastCall--;
    return upTo.filter((t, i) => !t.probe || i > lastCall).map(t => t.step);
}

function rightWord(family) {
    if (family.engineBug) return `**suspected ENGINE bug** (the ${family.right === 'unclear' ? 'right answer is unclear' : family.right + ' has it right'})`;
    if (family.right === 'engine') return 'the engine is right';
    if (family.right === 'mock') return 'the mock is right';
    return 'unclear which side is right';
}

export function writeReport({ results, walk, keyDrift, known, knownWalk, q, notes = null, noteTitle = 'note' }) {
    const lines = [];
    const out = (line = '') => lines.push(line);
    const passOf = new Map(results.passes.map(p => [p.name, p]));
    const records = results.records;
    const byFamily = new Map();
    const unclaimed = [];
    for (const r of records) {
        if (!r.claim) { unclaimed.push(r); continue; }
        const list = byFamily.get(r.claim.family) || [];
        list.push(r);
        byFamily.set(r.claim.family, list);
    }
    const walkEnds = (walk && walk.endings) || {};
    const families = known.filter(f => byFamily.has(f) || walkEnds[f.id]);
    const compares = results.passes.reduce((n, p) => n + p.compares, 0);

    out('# D1 — the mock against the engine: drift report');
    out();
    out(`Generated by \`node ui/differential/run.mjs --report <file>\` (do not edit by hand; edit`);
    out('`ui/differential/known_drift.mjs` and run again).');
    out();
    out(`- journeys: ${new Set(results.passes.map(p => p.journey)).size}, each run plain and again with an undo and a redo after every call`);
    out(`- compare points: ${compares}; Q = ${q} samples; the engine in 512-sample blocks`);
    out(`- diffs: ${records.length} — ${records.length - unclaimed.length} claimed by ${families.length} known-drift families, ${unclaimed.length} unclaimed`);
    if (walk) out(`- ${walk.summary}`);
    out();
    out('A **diff** is one fact (a key such as `@B.duration` or `island.masterPos`) at the first step where the');
    out('two sides part; `until` names the step where they agree again (none: to the end of the journey).');
    out('Nodes are named by the label their journey gave them (`@A`); sample counts print in Q where they are whole eighths.');
    out('The sequence of a diff is every step of its journey up to it; in a `+undo` pass each call was also followed');
    out('by an undo and a redo, which are left out of the sequence unless the diff sits on one.');
    out();

    // ---------------------------------------------------------------- summary
    out('## Summary');
    out();
    out(`| verb | drift | right | diffs |${notes ? ` ${noteTitle} |` : ''}`);
    out(`|---|---|---|---|${notes ? '---|' : ''}`);
    const byVerb = new Map();
    for (const f of families) {
        const list = byVerb.get(f.verb) || [];
        list.push(f);
        byVerb.set(f.verb, list);
    }
    for (const [verb, list] of byVerb) {
        for (const f of list) {
            const n = (byFamily.get(f) || []).length;
            const ends = (walkEnds[f.id] || []).length;
            out(`| \`${verb}\` | ${f.title} | ${f.engineBug ? '**ENGINE?**' : f.right} | ${n}${ends ? ` (+${ends} walks)` : ''} |` +
                (notes ? ` ${(notes[f.id] || '—').replace(/\|/g, '\\|')} |` : ''));
        }
    }
    out();

    const bugs = families.filter(f => f.engineBug);
    out('## Suspected engine bugs');
    out();
    if (!bugs.length) out('None.');
    for (const f of bugs) {
        out(`- **${f.title}** (\`${f.id}\`, under \`${f.verb}\`) — ${f.why}`);
    }
    out();

    // ---------------------------------------------------------------- by verb
    out('## Drift by verb');
    for (const [verb, list] of byVerb) {
        out();
        out(`### \`${verb}\``);
        for (const f of list) {
            const mine = byFamily.get(f) || [];
            out();
            out(`#### ${f.title}`);
            out();
            out(`- id \`${f.id}\` — ${rightWord(f)}: ${f.why}`);
            if (notes && notes[f.id]) out(`- ${noteTitle}: ${notes[f.id]}`);
            const everywhere = mine.filter(r => r.claim.kind === 'everywhere');
            const sited = mine.filter(r => r.claim.kind === 'site');
            if (everywhere.length) {
                const first = everywhere[0];
                const pass = passOf.get(first.journey);
                const inJourneys = new Set(everywhere.map(r => r.journey.replace(/ \+undo$/, ''))).size;
                out(`- claimed wherever it appears: ${everywhere.length} diffs in ${inJourneys} journeys. The shortest way there:`);
                const shortest = everywhere.reduce((a, b) => (b.at < a.at ? b : a));
                const sp = passOf.get(shortest.journey) || pass;
                out(`  - \`${shortest.journey}\`: ${sequenceTo(sp, shortest).map(x => `\`${x}\``).join(' → ') || '(the empty session)'}`);
                out(`  - \`${shortest.key}\`: engine ${cell(shortest.engine)}, mock ${cell(shortest.mock)}` +
                    (shortest.until ? ` — until \`${shortest.until}\`` : ''));
                const values = new Map();
                for (const r of everywhere) {
                    const k = `${r.field}: engine ${cell(r.engine)}, mock ${cell(r.mock)}`;
                    values.set(k, (values.get(k) || 0) + 1);
                }
                const top = [...values.entries()].sort((a, b) => b[1] - a[1]).slice(0, 6);
                out(`  - values seen: ${top.map(([k, n]) => `${k} (×${n})`).join('; ')}${values.size > 6 ? `; … ${values.size - 6} more` : ''}`);
            }
            const byJourney = new Map();
            for (const r of sited) {
                const list2 = byJourney.get(r.journey) || [];
                list2.push(r);
                byJourney.set(r.journey, list2);
            }
            for (const [journey, list2] of byJourney) {
                const pass = passOf.get(journey);
                const lastRec = list2.reduce((a, b) => (b.at > a.at ? b : a));
                out();
                out(`\`${journey}\` — ${sequenceTo(pass, lastRec).map(x => `\`${x}\``).join(' → ')}`);
                out();
                out('| at step | fact | engine | mock | until |');
                out('|---|---|---|---|---|');
                for (const r of list2) {
                    out(`| \`${r.step}\` | \`${r.key}\` | ${cell(r.engine)} | ${cell(r.mock)} | ${r.until ? `\`${r.until}\`` : '—'} |`);
                }
            }
            const ends = walkEnds[f.id] || [];
            if (ends.length) {
                out();
                out(`Random walks that ended here: ${ends.length} — e.g. \`${ends[0].name}\` after ${ends[0].ops} ops: ` +
                    `\`${ends[0].record.key}\` engine ${cell(ends[0].record.engine)}, mock ${cell(ends[0].record.mock)}.`);
            }
        }
    }
    out();

    // -------------------------------------------------------------- unclaimed
    out('## Unclaimed diffs');
    out();
    if (!unclaimed.length) out('None: every diff of this run is claimed above.');
    else {
        out('| journey | at step | fact | engine | mock |');
        out('|---|---|---|---|---|');
        for (const r of unclaimed) out(`| \`${r.journey}\` | \`${r.step}\` | \`${r.key}\` | ${cell(r.engine)} | ${cell(r.mock)} |`);
    }
    out();

    // ------------------------------------------------------------------- walk
    if (walk) {
        out('## The random walk');
        out();
        out(walk.summary + '.');
        out();
        if (walk.findings.length) {
            out('Findings (unclaimed, shrunk):');
            for (const f of walk.findings) {
                if (f.error) { out(`- \`${f.name}\`: harness error — ${f.error.split('\n')[0]}`); continue; }
                out(`- \`${f.name}\`${f.also.length ? ` (and ${f.also.length} more walks)` : ''}: \`${f.record.key}\` engine ${cell(f.record.engine)}, mock ${cell(f.record.mock)} at \`${f.record.step}\``);
                out(`  - minimal sequence: ${f.log.map(x => `\`${x}\``).join(' ; ')}`);
            }
        } else {
            out('No finding: every walk either ran to its end or ended at a diff a known family claims');
            out(`(the rules are \`KNOWN_WALK\` in known_drift.mjs: ${knownWalk.length}).`);
        }
        out();
    }

    // --------------------------------------------------------------- key sets
    out('## Published keys only one side has');
    out();
    out('Raw keys of getGraphState seen on one side and never on the other, per record kind (values are not');
    out('compared here; a key the mock omits until first written counts as published once it is).');
    out();
    out('| record | engine only | mock only |');
    out('|---|---|---|');
    for (const [kind, sets] of Object.entries(keyDrift)) {
        out(`| ${kind} | ${sets.engineOnly.map(k => `\`${k}\``).join(' ') || '—'} | ${sets.mockOnly.map(k => `\`${k}\``).join(' ') || '—'} |`);
    }
    out();

    // ------------------------------------------------------------ not drift
    out('## Differences the harness does not count');
    out();
    out('The two backends differ here by construction; the normaliser reads past each (the field table below');
    out('says where), so none of them is a diff above.');
    out();
    out('- **An arm is the audio thread\'s to start.** After `startRecordingInNode` the engine publishes the take as');
    out('  pending until its next block picks it up; the mock, with no audio thread, publishes it capturing at once.');
    out('  At a compare point right after a verb the three take flags fold into one `hot`; they are compared one by');
    out('  one after every advance.');
    out('- **The recording view switches a block late.** The engine\'s audio thread freezes and releases the');
    out('  cursor\'s recording view, so between a take verb and the next block `masterPos` still shows the view the');
    out('  thread last set. It is compared after every advance, and after a verb only when no take verb came since.');
    out('- **A pause has a tail.** The engine\'s transport runs on for one declick fade, to the end of that block,');
    out('  after `togglePlayback`; the harness moves the mock\'s clock by what the engine\'s transport moved.');
    out('- **The window phase is one block old** in the engine, and does not move while a take is up on the node;');
    out('  it is compared within one block, at block points, off the nodes under a take.');
    out('- **Absolute clocks.** The engine\'s clock is never reset; the mock restarts its own at the first arm. Every');
    out('  position is compared from the island zero, and before the island has one, not at all.');
    out('- **Answers of void verbs.** The engine answers `true` for "the call arrived"; the mock answers ids,');
    out('  nothing, or a refusal. Only the verbs with a shared return contract are compared.');
    out();

    if (notes && notes._appendix) {
        out(notes._appendix.trim());
        out();
    }

    // ------------------------------------------------------------- the fields
    out('## What is compared');
    out();
    out('| where | field | compared? | note |');
    out('|---|---|---|---|');
    for (const row of FIELDS) {
        const read = typeof row.read === 'function' || typeof row.readMany === 'function';
        out(`| ${row.on} | \`${row.field}\` | ${read ? 'yes' : row.note.startsWith('excluded') ? 'no' : 'derived'} | ${row.note.replace(/\|/g, '\\|')} |`);
    }
    out();
    return lines.join('\n') + '\n';
}
